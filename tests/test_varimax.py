"""Regression tests for Orthogonal Varimax subspace rotation (`pysimlr.svd.varimax`).

Validates:
1. Exact numerical agreement between `pysimlr.svd.varimax` (fallback and backend)
   and `nsa_flow.linalg.varimax` across dtypes and shapes.
2. Exact numerical agreement (up to column sign and permutation) against golden
   `R stats::varimax(E, normalize=TRUE, eps=1e-6)` reference loadings and against
   a live `Rscript` invocation when R is installed.
3. Exact preservation of column orthonormality (`V^T V = I_k`) and subspace
   projection (`V V^T = E E^T`), plus elimination of the Perron-Frobenius
   all-positive constant mode (`1 / sqrt(p)` -> localized axes).
4. `simlr(..., varimax=True)` vs `simlr(..., varimax=False)` behavior on
   non-negative bases.
"""

import shutil
import subprocess
import numpy as np
import pytest
import torch
from scipy.optimize import linear_sum_assignment

from pysimlr.svd import (varimax, varimax_rotation, _canonical_sign,
                         _varimax_rotation_torch, _varimax_torch)
from pysimlr.simlr import simlr


# Golden reference generated by R 4.x `stats::varimax(E, normalize=TRUE, eps=1e-6)`
# on the deterministic 8x3 orthonormal basis E below.
R_INPUT_E = np.array([
    [ 0.35355339,  0.50000000,  0.28867513],
    [ 0.35355339,  0.50000000, -0.28867513],
    [ 0.35355339, -0.50000000,  0.28867513],
    [ 0.35355339, -0.50000000, -0.28867513],
    [ 0.35355339,  0.00000000,  0.57735027],
    [ 0.35355339,  0.00000000, -0.57735027],
    [ 0.35355339,  0.00000000,  0.00000000],
    [ 0.35355339,  0.00000000,  0.00000000],
], dtype=np.float64)


def _r_stats_varimax_numpy(L: np.ndarray, normalize: bool = True, eps: float = 1e-6, maxit: int = 1000):
    """Line-for-line port of R `stats::varimax` (verified < 1e-6 against R in nsa_flow)."""
    x = np.array(L, dtype=np.float64, copy=True)
    nc = x.shape[1]
    if nc < 2:
        return x, np.eye(nc)
    sc = None
    if normalize:
        sc = np.sqrt((x ** 2).sum(1))
        sc[sc == 0] = 1.0
        x = x / sc[:, None]
    p = x.shape[0]
    T, d = np.eye(nc), 0.0
    for _ in range(maxit):
        z = x @ T
        B = x.T @ (z ** 3 - z @ np.diag((z ** 2).sum(0)) / p)
        u, s, vt = np.linalg.svd(B)
        T = u @ vt
        dpast, d = d, float(s.sum())
        if d <= dpast * (1.0 + eps):
            break
    z = x @ T
    if normalize:
        z = z * sc[:, None]
    return z, T


def _align_columns(A: np.ndarray, B: np.ndarray) -> np.ndarray:
    """Permute and sign-flip columns of A to best match B."""
    cross = np.abs(B.T @ A)
    row_ind, col_ind = linear_sum_assignment(-cross)
    A_perm = A[:, col_ind]
    signs = np.sign((A_perm * B).sum(axis=0, keepdims=True))
    signs[signs == 0] = 1.0
    return A_perm * signs


def test_pysimlr_varimax_matches_nsa_flow_linalg_varimax_exactly():
    """Fallback PyTorch implementation in `pysimlr.svd` must match `nsa_flow.linalg.varimax`."""
    nsa_linalg = pytest.importorskip("nsa_flow.linalg")
    gen = torch.Generator().manual_seed(42)
    raw = torch.randn(30, 4, generator=gen, dtype=torch.float64)
    E, _ = torch.linalg.qr(raw)

    # 1. Direct call (delegates to nsa_flow)
    V_delegated = varimax(E, normalize=True, eps=1e-6, max_iter=100, canonical_sign=True)
    V_nsa = nsa_linalg.varimax(E, normalize=True, eps=1e-6, max_iter=100, canonical_sign=True)
    assert torch.allclose(V_delegated, V_nsa, atol=1e-12)

    # 2. The pure-PyTorch implementations themselves. This used to call the
    # public `varimax_rotation`, which dispatches to nsa_flow whenever it is
    # installed -- so it compared nsa_flow with itself and never exercised
    # the PyTorch path it claimed to test.
    R_py = _varimax_rotation_torch(E, normalize=True, eps=1e-6, max_iter=100)
    R_nsa = nsa_linalg.varimax_rotation(E, normalize=True, eps=1e-6, max_iter=100)
    assert torch.allclose(R_py, R_nsa, atol=1e-10)
    V_py = _varimax_torch(E, normalize=True, eps=1e-6, max_iter=100, canonical_sign=True)
    assert torch.allclose(V_py, V_nsa, atol=1e-10)


def test_varimax_matches_r_stats_varimax_reference():
    """`pysimlr.svd.varimax` must match R `stats::varimax` to < 1e-6 on orthonormal and factor loadings."""
    for seed in (0, 7, 19):
        rng = np.random.default_rng(seed)
        A = rng.standard_normal((25, 4))
        Q, _ = np.linalg.qr(A)
        E_t = torch.tensor(Q, dtype=torch.float64)

        V_py = varimax(E_t, normalize=True, eps=1e-6, max_iter=1000, canonical_sign=False).numpy()
        V_r, _ = _r_stats_varimax_numpy(Q, normalize=True, eps=1e-6, maxit=1000)

        V_py_aligned = _align_columns(V_py, V_r)
        assert np.max(np.abs(V_py_aligned - V_r)) < 1e-6

    # Also check against live Rscript if installed on the system
    if shutil.which("Rscript") is not None:
        E_t = torch.tensor(R_INPUT_E, dtype=torch.float64)
        V_py = varimax(E_t, normalize=True, eps=1e-6, max_iter=1000, canonical_sign=False).numpy()
        r_vals = ",".join(f"{x:.16g}" for x in R_INPUT_E.ravel(order="F"))
        r_code = (
            f"E <- matrix(c({r_vals}), nrow=8, ncol=3); "
            f"vm <- stats::varimax(E, normalize=TRUE, eps=1e-6)$loadings; "
            f"cat(paste(sprintf('%.12f', as.vector(vm)), collapse=','))"
        )
        proc = subprocess.run(["Rscript", "-e", r_code], capture_output=True, text=True, check=True)
        V_r_live = np.fromstring(proc.stdout.strip(), sep=",").reshape((8, 3), order="F")
        V_py_aligned = _align_columns(V_py, V_r_live)
        assert np.max(np.abs(V_py_aligned - V_r_live)) < 1e-6


def test_varimax_preserves_subspace_and_breaks_perron_frobenius_mean_mode():
    """Varimax preserves V^T V = I_k and V V^T = E E^T while rotating the flat mean vector."""
    # Construct 3 disjoint block indicators of length 12, then rotate by an orthogonal
    # matrix whose first column mixes all 3 blocks into a flat all-positive mean mode.
    V_blocks = torch.zeros(12, 3, dtype=torch.float64)
    for j in range(3):
        V_blocks[4 * j:4 * (j + 1), j] = 0.5  # unit norm per column
    H = torch.tensor([
        [1.0 / np.sqrt(3),  1.0 / np.sqrt(2),  1.0 / np.sqrt(6)],
        [1.0 / np.sqrt(3), -1.0 / np.sqrt(2),  1.0 / np.sqrt(6)],
        [1.0 / np.sqrt(3),  0.0,              -2.0 / np.sqrt(6)],
    ], dtype=torch.float64)
    E_t = V_blocks @ H.T  # First column is flat 1/sqrt(12) across all 12 rows!
    assert torch.allclose(E_t.T @ E_t, torch.eye(3, dtype=torch.float64), atol=1e-7)

    V_t = varimax(E_t, normalize=True, eps=1e-12, canonical_sign=True)
    # 1. Exact column orthonormality preserved
    assert torch.allclose(V_t.T @ V_t, torch.eye(3, dtype=torch.float64), atol=1e-7)
    # 2. Exact subspace projector preserved: V V^T == E E^T
    assert torch.allclose(V_t @ V_t.T, E_t @ E_t.T, atol=1e-7)
    # 3. Fourth-moment Varimax simplicity criterion strictly increases and recovers V_blocks
    def _kaiser_criterion(M):
        L2 = M ** 2
        return float(((L2 ** 2).mean(dim=0) - (L2.mean(dim=0) ** 2)).sum())
    assert _kaiser_criterion(V_t) > _kaiser_criterion(E_t) + 0.02
    V_aligned = _align_columns(V_t.numpy(), V_blocks.numpy())
    assert np.allclose(V_aligned, V_blocks.numpy(), atol=1e-5)


def test_simlr_varimax_flag_controls_nonnegative_initialization():
    """`simlr(..., varimax=True)` vs `varimax=False` produces distinct non-negative initializations."""
    gen = torch.Generator().manual_seed(12)
    # Construct two views with a strong positive global background mode + 3 local modules
    u_true = torch.rand(90, 3, generator=gen)
    views = []
    for p in (24, 18):
        v_true = torch.zeros(p, 3)
        block = p // 3
        for j in range(3):
            v_true[j * block:(j + 1) * block, j] = 1.0
        global_mode = torch.ones(90, 1) @ torch.ones(1, p) * 1.5
        x = global_mode + u_true @ v_true.T + 0.1 * torch.randn(90, p, generator=gen)
        views.append(x)

    res_vmx = simlr(views, k=3, iterations=3, positivity="positive",
                    sparseness=None, varimax=True, learning_rate=0.01)
    res_legacy = simlr(views, k=3, iterations=3, positivity="positive",
                       sparseness=None, varimax=False, learning_rate=0.01)
    assert not torch.allclose(res_vmx["v"][0], res_legacy["v"][0])


# --------------------------------------------------------------------------
# dispatch: explicit, validated, and errors are not swallowed
