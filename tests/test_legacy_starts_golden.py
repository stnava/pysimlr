"""Pin the 0.40.0 starting bases and short fits for every legacy ``initialization_type``.

``golden_init_v040.npz`` was generated by ``tests/data/make_golden_init_v040.py`` from
commit 2c3af72 (v0.40.0). Exact equality (not allclose): the request requires the
current starts to stay available by name and bit-identical.
"""
import importlib.util
import pathlib

import numpy as np
import pytest
import torch

import pysimlr
from pysimlr.simlr import initialize_simlr

_DATA = pathlib.Path(__file__).parent / "data"
_spec = importlib.util.spec_from_file_location("make_golden_init_v040", _DATA / "make_golden_init_v040.py")
_gen = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_gen)
GOLD = np.load(_DATA / "golden_init_v040.npz")


@pytest.mark.parametrize("pos", _gen.POSITIVITIES)
@pytest.mark.parametrize("it", _gen.LEGACY_INITS)
def test_initialize_simlr_matches_v040(it, pos):
    views = _gen.golden_views()
    dom = _gen.golden_domain(views) if it == "domain" else None
    b = initialize_simlr(views, 2, initialization_type=it, positivity=pos,
                         generator=torch.Generator().manual_seed(0), sparseness=0.5, domain_matrices=dom)
    for m, v in enumerate(b):
        np.testing.assert_array_equal(np.asarray(v, dtype=np.float64), GOLD[f"init|{it}|{pos}|v{m}"])


@pytest.mark.parametrize("pos", _gen.FIT_POSITIVITIES)
@pytest.mark.parametrize("it", _gen.LEGACY_INITS)
def test_simlr_fit_matches_v040(it, pos):
    views = _gen.golden_views()
    dom = _gen.golden_domain(views) if it == "domain" else None
    r = pysimlr.simlr(views, 2, iterations=8, initialization_type=it, random_state=0,
                      sparseness=0.5, positivity=pos, domain_matrices=dom)
    for m, v in enumerate(r["v"]):
        np.testing.assert_array_equal(np.asarray(v, dtype=np.float64), GOLD[f"fit|{it}|{pos}|v{m}"])
    np.testing.assert_array_equal(np.asarray(r["u"], dtype=np.float64), GOLD[f"fit|{it}|{pos}|u"])
